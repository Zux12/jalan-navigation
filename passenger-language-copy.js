  function clock(text) {
    const match = /^(\d{1,2}):(\d{2})\s*([ap])\.?m\.?$/i.exec(text);
    if (!match) return text;
    const hour = Number(match[1]);
    const morning = match[3].toLowerCase() === 'a';
    let period;
    if (morning) period = hour === 12 ? 'tengah malam' : 'pagi';
    else if (hour === 12 || hour === 1) period = 'tengah hari';
    else period = hour < 7 ? 'petang' : 'malam';
    return match[1] + ':' + match[2] + ' ' + period;
  }

