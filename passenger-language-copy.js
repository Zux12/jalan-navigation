  function translate(english) {
    if (typeof english !== 'string' || !english) return english;
    if (Object.hasOwn(labels, english)) return labels[english];
    for (const [pattern, render] of templates) {
      const match = pattern.exec(english);
      if (match) return render(...match);
    }
    // These compound rows consist entirely of application-controlled fields.
    // Splitting arbitrary strings would damage a custom name such as "Home · Work".
    if (english.includes(' · ') && (
      / · (?:\d+ (?:community )?reports?\b|reported by \d+ users?\b|unverified demo report$|expires \d)/.test(english) ||
      /^(?:Arrival approx\. \d|(?:light|moderate|heavy|closed) traffic · |\d+(?:\.\d+)? (?:km|m) · (?:Traffic estimate|No traffic)$|\d+(?: hr \d+)? min · [+]\d+ min$)/.test(english)
    )) {
      return english.split(' · ').map(translate).join(' · ');
    }
    return english;
  }

